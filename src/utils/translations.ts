export function formatMoney(
  amountInUSD: number,
  currency: Currency = 'USD',
  rates = { USD_KHR: 4100, USD_KRW: 1380 }
): string {
  if (currency === 'KHR') {
    const khr = Math.round(amountInUSD * rates.USD_KHR);
    return `${khr.toLocaleString()} ៛`;
  }
  if (currency === 'KRW') {
    const krw = Math.round(amountInUSD * rates.USD_KRW);
    return `₩${krw.toLocaleString()}`;
  }
  return `$${amountInUSD.toFixed(2)}`;
}
